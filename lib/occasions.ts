// Occasion landing pages (/letters/[occasion]).
// Each occasion maps to an existing letter type so the page can show real
// templates and deep-link into /write with one preselected.

export type Occasion = {
  slug: string
  type: string            // LETTER_TYPES id
  emoji: string
  name: string            // short label, used in lists and breadcrumbs
  h1: string
  subheading?: string     // optional above-the-fold value-prop line under the H1
  metaTitle: string
  metaDescription: string
  intro: string[]         // 3 paragraphs
  whatToSay: string[]     // 5-6 concrete prompts
  openers: string[]       // 3 example opening lines the reader can steal
  avoid: string           // one honest "don't do this" line
  example: { generic: string; better: string; why: string } // occasion-specific before/after
  fillIn: string[]        // printable fill-in-the-blank letter, bracketed slots
  faq: { q: string; a: string }[]  // 4-5 questions specific to this occasion
  closing: string         // occasion-specific closing CTA copy
  related: string[]       // slugs
  moat?: { heading: string; body: string } // optional differentiator callout
  // Optional "when is it?" block for occasions whose date moves, or differs by
  // country (Grandparents Day is September in the US and October in the UK).
  dates?: {
    heading: string
    rows: { region: string; date: string; rule: string }[]
    note?: string
  }
  // Optional explicit template list (TEMPLATES ids). When present, the occasion
  // page shows ONLY these templates instead of every template of `type` —
  // keeps occasion pages that share a letter type from duplicating each other.
  templateIds?: string[]
  // Optional full-text template library (TEMPLATES ids that carry a `body`).
  // Rendered in full, high on the page, with copy buttons — for occasions whose
  // searchers want the actual letter, not a description of one.
  templateLibrary?: { heading: string; intro: string; ids: string[] }
  // Optional contextual in-prose link to a related page, rendered as a body
  // paragraph under the intro. Used for internal linking with exact anchors.
  proseLink?: { before: string; anchor: string; href: string; after: string }
}

